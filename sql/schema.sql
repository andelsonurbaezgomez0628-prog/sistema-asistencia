-- Esquema PostgreSQL para Asistencia Escolar Inteligente.
-- El instalador Node conserva datos existentes y solo ejecuta este archivo
-- en una base vacia o con confirmacion destructiva.

DROP TABLE IF EXISTS alertas;
DROP TABLE IF EXISTS asistencia;
DROP TABLE IF EXISTS estudiantes;
DROP TABLE IF EXISTS secciones;
DROP TABLE IF EXISTS cursos;
DROP TABLE IF EXISTS usuarios;
DROP TABLE IF EXISTS sesiones;

CREATE TABLE usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  cedula VARCHAR(20) NOT NULL UNIQUE,
  usuario VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  rol VARCHAR(10) NOT NULL DEFAULT 'docente' CHECK (rol IN ('admin', 'docente')),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_el TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cursos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE,
  descripcion VARCHAR(255),
  creado_el TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE secciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL,
  curso_id INTEGER NOT NULL REFERENCES cursos(id),
  docente_id INTEGER NOT NULL REFERENCES usuarios(id),
  anio_escolar VARCHAR(9) NOT NULL DEFAULT '2025-2026',
  CONSTRAINT uq_seccion_curso UNIQUE (nombre, curso_id)
);

CREATE TABLE estudiantes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_lista SMALLINT NOT NULL CHECK (numero_lista BETWEEN 1 AND 40),
  nombre VARCHAR(80) NOT NULL,
  apellido VARCHAR(80) NOT NULL,
  fecha_nacimiento DATE,
  seccion_id INTEGER NOT NULL REFERENCES secciones(id),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_el TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_estudiante_seccion_lista UNIQUE (seccion_id, numero_lista)
);

CREATE TABLE asistencia (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id),
  fecha DATE NOT NULL,
  estado VARCHAR(12) NOT NULL CHECK (estado IN ('presente', 'tardanza', 'ausente', 'justificado')),
  observacion VARCHAR(255),
  creado_por INTEGER NOT NULL REFERENCES usuarios(id),
  creado_el TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_estudiante_fecha UNIQUE (estudiante_id, fecha)
);

CREATE INDEX idx_asistencia_fecha ON asistencia (fecha);

CREATE TABLE alertas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id INTEGER NOT NULL REFERENCES estudiantes(id),
  nivel VARCHAR(8) NOT NULL CHECK (nivel IN ('bajo', 'medio', 'alto')),
  faltas_30_dias SMALLINT NOT NULL CHECK (faltas_30_dias >= 0),
  racha_maxima SMALLINT NOT NULL CHECK (racha_maxima >= 0),
  mensaje TEXT NOT NULL,
  fecha_deteccion DATE NOT NULL,
  estado VARCHAR(10) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'atendida')),
  atendida_por INTEGER REFERENCES usuarios(id)
);

CREATE INDEX idx_alertas_estado_fecha ON alertas (estado, fecha_deteccion DESC);
